import Foundation          // for UserDefaults, FileManager, Data, URL
import TipKit              // for Tips.hideAllTipsForTesting
import Photo_Club_Hub_Data // for Organization

/// Screenshot pipeline (#776): Lets each screen signal "my target/preset content is now on screen"
/// to `capture-screenshots.sh`. Only does anything if the app was launched with `-initialTab`
/// (= app is in special screenshot mode).
///
/// The script polls for a marker file in the app's Documents directory (located via
/// `simctl get_app_container <UDID> <bundle> data`) instead of relying
/// on fixed `sleep`s, and fails the run if the marker doesn't appear before a timeout runs out.
///
/// Declared as a caseless `enum` (rather than a `struct`) to make it uninstantiable by design:
/// the compiler synthesises no `init`, so `ScreenshotReadiness()` would give a compile error.
/// Alternative to using a `struct`with an explicit `@available(*, unavailable)` workaround.
enum ScreenshotReadiness {

    // MARK: - initialize without using init()

    /// An organization for a screenshot targets. It is identified by name and town, as in the JSON:
    /// a name alone could recur in another town or in a template file ("Fotografiska New York" does).
    /// Compare with an `Organization` by converting it first: `OrganizationTarget(organization) == target`.
    struct OrganizationTarget: Equatable {
        let fullName: String
        let town: String

        init(fullName: String, town: String) {
            self.fullName = fullName
            self.town = town
        }

        init(_ organization: Organization) {
            self.init(fullName: organization.fullName, town: organization.town)
        }
    }

    /// The portfolio a Portfolio screen pushes, and the gallery image it shows (#777, #880).
    /// The image is named by its file name, not its position: a member adding images at the front of
    /// a gallery would shift every position, but leaves the file names alone.
    struct PortfolioImageTarget {
        /// The club's portfolios must be Juicebox-Pro galleries, which the screenshot code can tell to show a
        /// given image. Other clubs' portfolio pages can't be driven that way.
        let club: OrganizationTarget
        let memberName: String    // as `Photographer.fullNameFirstLast`
        let imageFileName: String // last path component of the image's URL in a gallery generated by Juicebox-Pro
    }

    /// The club of the Maps and Clubs screens and of every portfolio preset.
    static let targetClub = OrganizationTarget(fullName: "Fotogroep de Gender", town: "Eindhoven")

    /// Keyed by the lowercased `-initialTab` value. PortfolioPortrait and PortfolioLandscape (#880) differ in how the
    /// device is held: PortfolioLandscape turns it sideways (see `SinglePortfolioView`). The image itself can have
    /// either shape: PortfolioPortrait shows a landscape photo on an upright phone.
    private static let portfolioPresets: [String: PortfolioImageTarget] = [
        "portfolioviaclubs": PortfolioImageTarget(club: targetClub,
                                                  memberName: "Francien van Mil",
                                                  imageFileName: "2025_fgDeGenderExpo_123.jpg"),
        "portfolioviapeople": PortfolioImageTarget(club: targetClub,
                                                   memberName: "Francien van Mil",
                                                   imageFileName: "2025_fgDeGenderExpo_123.jpg"),
        "portfolioportrait": PortfolioImageTarget(club: targetClub,
                                                  memberName: "Lex Augusteijn",
                                                  imageFileName: "2025_LexAugusteijn_004.jpg"),
        "portfoliolandscape": PortfolioImageTarget(club: targetClub,
                                                   memberName: "Jelle van der Voort",
                                                   imageFileName: "2026_JelleVanDerVoort_01.jpg")
    ]

    /// The `-initialTab` launch argument, lowercased. Nil in normal use.
    private static var initialTab: String? {
        UserDefaults.standard.string(forKey: "initialTab")?.lowercased() // launch argument, not persisted
    }

    /// The preset of the current Portfolio screen, or nil when the app isn't capturing one.
    static var portfolioPreset: PortfolioImageTarget? {
        initialTab.flatMap { portfolioPresets[$0] }
    }

    /// The club whose members the Clubs tab waits for: the Clubs screen scrolls to it,
    /// and a Portfolio screen that starts from the Clubs tab pushes one of its members.
    static var clubsTabPresetClub: OrganizationTarget {
        portfolioPreset?.club ?? targetClub
    }

    /// The Portfolio screens that start from the Clubs tab; PortfolioViaPeople starts from the People tab.
    static var isPortfolioViaClubsTab: Bool {
        portfolioPreset != nil && initialTab != "portfolioviapeople"
    }

    private static let readyMarkerFileName = "screenshot-ready"

    /// One-stop startup hook, called once from `PhotoClubHubApp.init` so that file needs a
    /// single screenshot-related line: clears a stale readiness marker (see `reset`) and
    /// honors the `-suppressTips YES` launch argument by hiding all TipKit tips (#776).
    static func configureAtStartup() {
        reset()
        if UserDefaults.standard.bool(forKey: "suppressTips") { // launch arguments -> not persisted by UserDefaults
            Tips.hideAllTipsForTesting()
        }
    }

    /// Deletes a stale marker left behind by a previous launch. Called once at app startup.
    /// The capture script also removes the marker before each launch (belt and braces).
    static func reset() {
        guard UserDefaults.standard.string(forKey: "initialTab") != nil else { return }
        try? FileManager.default.removeItem(at: markerURL)
    }

    // MARK: - signaling when screens are available

    /// SinglePortfolioView's gallery jump serves every Portfolio screen; this signals whichever one is active.
    static func signalReadyForPortfolioPreset() {
        guard let initialTab, portfolioPresets[initialTab] != nil else { return }
        signalReady(for: initialTab)
    }

    /// Writes the marker file, but only if `screen` matches the `-initialTab` launch argument —
    /// so a screen that happens to appear while another screen is being captured cannot
    /// signal readiness on that screen's behalf.
    static func signalReady(for screen: String) {
        // `initialTab` launch argument not persisted by UserDefaults
        guard UserDefaults.standard.string(forKey: "initialTab")?.lowercased()
                == screen.lowercased() else { return }
        try? Data().write(to: markerURL) // empty file
    }

    private static var markerURL: URL {
        FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
            .appendingPathComponent(readyMarkerFileName)
    }

}
